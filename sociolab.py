import streamlit as st
import google.generativeai as genai
import pypdf

# 1. КОНФИГУРАЦИЯ НА ПРИЛОЖЕНИЕТО
st.set_page_config(page_title="SocioLab: Цифров учебник по ЕСИ", layout="wide")
st.title("SocioLab: Цифров учебник и методологичен тренажор")
st.subheader("Елементи на социологическото изследване (в традицията на Пиер Бурдийо)")

# 2. СВЪРЗВАНЕ С ИЗКУСТВЕНИЯ ИНТЕЛЕКТ
try:
    api_key = st.secrets["GEMINI_API_KEY"]
    genai.configure(api_key=api_key)
except KeyError:
    st.error("⚠️ Грешка: API ключът не е намерен в настройките (Secrets) на Streamlit Cloud!")

# ИЗВЛИЧАНЕ НА РЕАЛНИТЕ МОДЕЛИ
@st.cache_resource
def get_available_models():
    try:
        return [m.name.replace('models/', '') for m in genai.list_models() if 'generateContent' in m.supported_generation_methods]
    except Exception:
        return ["gemini-1.5-flash", "gemini-1.5-pro"] 

available_models = get_available_models()

# 3. ЛЯВА ЛЕНТА (ПОМОЩНИ МАТЕРИАЛИ И РЕЧНИК)
with st.sidebar:
    st.header("⚙️ Настройки")
    selected_model = st.selectbox(
        "Избери модел:", 
        available_models,
        index=available_models.index("gemini-1.5-flash") if "gemini-1.5-flash" in available_models else 0
    )
    
    st.markdown("---")
    st.header("📂 Теоретичен корпус")
    uploaded_file = st.file_uploader(
        "Качи текст, лекция или PDF за анализ:", 
        type=["txt", "md", "pdf"]
    )
    
    custom_corpus = ""
    if uploaded_file is not None:
        if uploaded_file.name.endswith(".pdf"):
            try:
                reader = pypdf.PdfReader(uploaded_file)
                for page in reader.pages:
                    text = page.extract_text()
                    if text:
                        custom_corpus += text + "\n"
                if len(custom_corpus) > 20000:
                    custom_corpus = custom_corpus[:20000] + "\n[...Текстът е съкратен автоматично...]"
                st.success("✅ PDF файлът е зареден успешно!")
            except Exception as e:
                st.error(f"Грешка при четене на PDF: {e}")
        else:
            custom_corpus = uploaded_file.read().decode("utf-8")
            if len(custom_corpus) > 20000:
                custom_corpus = custom_corpus[:20000] + "\n[...Текстът е съкратен...]"
            st.success("✅ Текстовият файл е зареден успешно!")

    st.markdown("---")
    st.header("📖 Речник на понятията")
    with st.expander("Основни категории по Бурдийо"):
        st.markdown("""
        * **Хабитус:** Система от трайни, инкорпорирани диспозиции, продукт на социалните структури и техен генератор.
        * **Поле:** Обособено социално пространство с относителна автономност и борби за специфични залози.
        * **Капитал:** Икономически, културен, социален или символичен ресурс, даващ власт в съответното поле.
        * **Схоластична илюзия (Skholè):** Приписване на отвлечени, академични мотиви на обикновените социални агенти.
        * **Епистемологичен скъс:** Откъсване от спонтанната социология и здравия разум чрез научно конструиране.
        * **Траектория:** Линията на социално движение през многоизмерното пространство.
        """)

    st.markdown("---")
    st.info("💡 **Режим:** Нулеви отклонения (temperature=0.0) за пълна академична стабилност.")

# 4. СТРУКТУРА НА УЧЕБНИКА (ТАБОВЕ)
tab0, tab1, tab2, tab3 = st.tabs([
    "📖 За учебника и методологията",
    "🔎 Модул 1: Рефлексивна социология", 
    "🎲 Модул 2: Релационна социология", 
    "🎯 Модул 3: Научният въпрос"
])

# --- ТАБ 0: УЧЕБНИК И МЕТОДОЛОГИЯ ---
with tab0:
    st.header("Добре дошли в интерактивния учебник по Социологика на ЕСИ")
    st.write("""
    Този цифров учебник е създаден да подпомогне студентите в усвояването на изследователското занаятчииство в социологията, вкоренено в епистемологичната традиция на **Пиер Бурдийо, Жан-Клод Пасро и Жан-Клод Шамборедо**.
    """)
    
    st.markdown("### 🧭 Основни принципи на упътването:")
    st.markdown("""
    1. **Отказ от спонтанната социология:** Научното изследване започва с разкъсване на илюзиите на здравия разум, битовия морализъм и есенциализма.
    2. **Релационно мислене:** Светът на социалното не се състои от изолирани индивиди или готови статистически единици, а от мрежи от обективни отношения (пространства на позиции).
    3. **Рефлексивност:** Изследователят трябва непрекъснато да обективира собствената си позиция, академичен хабитус и социални предразсъдъци спрямо обекта на изследване.
    """)

# --- МОДУЛ 1: РЕФЛЕКСИВНА СОЦИОЛОГИЯ ---
with tab1:
    st.header("Модул 1: Рефлексивна социология (Епистемологичен скъс)")
    st.write("Анализ на темата през детекцията на предразсъдъци и академичната рефлексивност.")
    
    user_topic_1 = st.text_area(
        "Опиши социологическия си проблем/тема:",
        placeholder="Например: Влиянието на социалните мрежи върху политическата активност на младите",
        key="topic_mod1"
    )
    
    if st.button("Тествай Модул 1 (Рефлексивен анализ)"):
        if user_topic_1:
            with st.spinner("Извършване на епистемологичен разрез..."):
                system_prompt_1 = f"""
                ТИ СИ: Методологичен ментор в традицията на Пиер Бурдийо и Жан-Клод Пасро.
                
                ДОПЪЛНИТЕЛЕН ТЕОРЕТИЧЕН КОРПУС ОТ ПРЕПОДВАТЕЛЯ:
                {custom_corpus if custom_corpus else "Няма качен външен файл. Използвай класическата рамка на Бурдийо."}
                
                СТРОГИ ТЕОРЕТИЧНИ ИЗИСКВАНИЯ:
                1. Никога не дефинирай хабитус като "нагласа" или "психологическа мотивация". Хабитусът е система от трайни, инкорпорирани диспозиции.
                2. Не допускай плъзгане към пазарен функционализъм, битов психологизъм или наивен емпиризъм.
                
                ФОРМАТ НА ОТГОВОР:
                1. 🛑 1. ДЕТЕКТОР ЗА ЗДРАВ РАЗУМ: Анализирай дали формулировката съдържа елементи на спонтанна социология (морализиране, есенциализъм, психологизиране).
                2. 🎓 2. СХОЛАСТИЧНА ИЛЮЗИЯ (Skholè): Провери дали темата не страда от излишна абстракция или приписване на чисто рационални мотиви на агентите.
                3. 🪞 3. СОБСТВЕНА ПОЗИЦИЯ И АКАДЕМИЧНА РЕФЛЕКСИВНОСТ: Обективирай позицията на изследователя спрямо тази тема и влиянието на неговия културен капитал.
                4. 🎯 ПРЕХОД КЪМ СОЦИОЛОГИЧЕСКИ ВЪПРОС: 
                   - Извади на преден план скритите социологически понятия, базирани и на качените материали.
                   - Разбий въпроса на система от конкретни аналитични подвъпроси за емпирично изследване.
                """
                try:
                    model_1 = genai.GenerativeModel(selected_model, system_instruction=system_prompt_1)
                    response_1 = model_1.generate_content(
                        user_topic_1, 
                        generation_config={"temperature": 0.0}
                    )
                    st.markdown(response_1.text)
                except Exception as e:
                    st.error(f"⚠️ Избраният модел ({selected_model}) не успя да обработи заявката. Възможно е да е експериментален или да не поддържа системни инструкции. Моля, избери 'gemini-1.5-pro' или 'gemini-1.5-flash' от менюто вляво.\n\n*(Технически детайли: {e})*")

# --- МОДУЛ 2: РЕЛАЦИОННА СОЦИОЛОГИЯ ---
with tab2:
    st.header("Модул 2: Релационна социология (Конструиране на обекта и съвкупността)")
    st.write("Изграждане на релационното пространство на обекта, корпуса от позиции и разграничението на извадката.")
    
    user_topic_2 = st.text_area(
        "Въведи темата за релационно конструиране:",
        placeholder="Например: Влиянието на социалните мрежи върху политическата активност на младите",
        key="topic_mod2"
    )
    
    if st.button("Тествай Модул 2 (Релационен обект и корпус)"):
        if user_topic_2:
            with st.spinner("Конструиране на релационния обект и съвкупността..."):
                system_prompt_module_2 = f"""
                ТИ СИ: Методологичен ментор по емпирична социология в традицията на Пиер Бурдийо.
                
                ДОПЪЛНИТЕЛЕН ТЕОРЕТИЧЕН КОРПУС ОТ ПРЕПОДВАТЕЛЯ:
                {custom_corpus if custom_corpus else "Няма качен външен файл. Използвай релационната методология на Бурдийо."}
                
                СТРОГИ ТЕОРЕТИЧНИ ИЗИСКВАНИЯ ЗА МОДУЛ 2:
                Приложи релационната методология към темата, като обхванеш следните компоненти. ЗАДЪЛЖИТЕЛНО разграничавай строго единиците на извадка (рамката и практическите инструменти за достъп) от единиците на анализ (самите структурни позиции и аналитични конструкти, които изследваме).
                
                ФОРМАТ НА ОТГОВОР:
                1. 🏗️ 1. РЕЛАЦИОННО КОНСТРУИРАНЕ НА ЕМПИРИЧНИЯ ОБЕКТ: Обясни как концепцията се превръща в изследване на обективни отношения и структури на полето (отхвърляйки счетоводната статистика).
                2. 🌐 2. КОРПУС ОТ ПОЗИЦИИ И ГЕНЕРАЛНА СЪВКУПНОСТ: Покажи защо съвкупността не е статистическа сума от индивиди, а структуриран корпус от позиции в социалното пространство (структурни хомологии).
                3. 📊 3. ЕДИНИЦИ НА ИЗВАДКА СРЕЩУ ЕДИНИЦИ НА АНАЛИЗ: Направи строго разграничение между единиците на извадка (практическите инструменти за достъп) и единиците на анализ (структурните позиции и отношения).
                """
                try:
                    model_module_2 = genai.GenerativeModel(selected_model, system_instruction=system_prompt_module_2)
                    response_module_2 = model_module_2.generate_content(
                        user_topic_2, 
                        generation_config={"temperature": 0.0}
                    )
                    st.markdown(response_module_2.text)
                except Exception as e:
                    st.error(f"⚠️ Избраният модел ({selected_model}) не успя да обработи заявката. Моля, избери 'gemini-1.5-pro' или 'gemini-1.5-flash'.\n\n*(Технически детайли: {e})*")

# --- МОДУЛ 3 ---
with tab3:
    st.header("3. Раждането на социологическия въпрос")
    st.info("В процес на разработка...")
